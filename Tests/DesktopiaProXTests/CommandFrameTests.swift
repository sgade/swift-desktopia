import DesktopiaProX
import Testing

struct CommandFrameTests {

    @Test(arguments: [
        (Command.heartbeat, [0xF1, 0xF1, 0xAA, 0x04, 0x00, 0x00, 0x00, 0x06, 0xB4, 0x7E] as [UInt8]),
        (Command.showStatus, [0xF1, 0xF1, 0x07, 0x00, 0x07, 0x7E]),
        (Command.saveToMemoryPosition1, [0xF1, 0xF1, 0x03, 0x00, 0x03, 0x7E]),
        (Command.saveToMemoryPosition2, [0xF1, 0xF1, 0x04, 0x00, 0x04, 0x7E]),
        (Command.moveUp, [0xF1, 0xF1, 0x01, 0x00, 0x01, 0x7E]),
        (Command.moveDown, [0xF1, 0xF1, 0x02, 0x00, 0x02, 0x7E]),
        (Command.moveToMemoryPosition1, [0xF1, 0xF1, 0x05, 0x00, 0x05, 0x7E]),
        (Command.moveToMemoryPosition2, [0xF1, 0xF1, 0x06, 0x00, 0x06, 0x7E]),
        (Command.moveToMemoryPosition3, [0xF1, 0xF1, 0x27, 0x00, 0x27, 0x7E])
    ])
    func buildsTheFrame(command: Command, expected: [UInt8]) {
        #expect(command.buildFrame() == expected)
    }

    @Test func decodesAHeightFrame() throws {
        let frame: [UInt8] = [0xF2, 0xF2, 0x01, 0x03, 0x02, 0xCF, 0x07, 0xDC, 0x7E]

        let command = try Command(from: frame)

        #expect(command.source == .desk)
        #expect(command.data == [0x03, 0x02, 0xCF, 0x07, 0xDC])
    }

}
